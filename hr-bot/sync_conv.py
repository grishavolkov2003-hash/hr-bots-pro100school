for uid, messages in updates.items():
    row = conn.execute("SELECT conversation FROM candidates WHERE user_id=?", (uid,)).fetchone()
    if not row:
        print(f"  SKIP uid={uid} - not in DB")
        continue
    conv = json.loads(row["conversation"]) if row["conversation"] else []
    for role, text in messages:
        conv.append({"role": role, "content": text})
    conn.execute(
        "UPDATE candidates SET conversation=?, updated_at=datetime('now') WHERE user_id=?",
        (json.dumps(conv, ensure_ascii=False), uid)
    )
    print(f"  Updated uid={uid}: +{len(messages)} messages")

conn.commit()
